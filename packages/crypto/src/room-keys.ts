/**
 * Room keys in the browser (cryptographic-architecture section 7, ADR-015 section 4, Phase 6).
 *
 *   RKM_v  32 random bytes, generated by the creating browser, never sent or stored in plaintext
 *   RKC_v  = HKDF(RKM_v, info = cm.room.commitment {roomId, keyVersion})   public commitment
 *   RWK_v  = HKDF(RKM_v, info = cm.room.dek-wrap-key {roomId, keyVersion}) wraps DEKs (Phase 7)
 *   RSC_v  = HKDF(RKM_v, info = cm.room.safety-code {roomId, keyVersion})  Room Safety Code
 *   envelope = RSA-OAEP(recipient key, RKM_v, label = cm.room.envelope
 *              {roomId, keyVersion, recipientUserId, recipientKeyId, suite})
 *
 * A key version is used only after the verification rule of ADR-015 section 4 (with the Phase 6
 * clarification approved by the project owner for invited members) holds:
 *   1. the creator's public identity verifies (binding signature, fingerprint);
 *   2. the key-version statement verifies under the creator's signing key;
 *   3. the creator's OWNER or ADMIN authority follows from signed grants back to the signed
 *      genesis statement; version 1 is created only by the genesis creator;
 *   4. this client is authorized to hold the key: its own user and identity key are in the
 *      signed recipient list, OR it is the subject of a signed membership grant whose grantor's
 *      authority follows from the chain (an invited member, who joined after the version was
 *      signed);
 *   5. its own envelope opens under the label that names this room, version and identity;
 *   6. the decrypted RKM_v reproduces the signed commitment (CD-24); a rekeyed version must also
 *      differ from the previous one (reuse check, key-lifecycle 1.4).
 * Any failure refuses the key with KEY_AUTHENTICATION_FAILED, or KEY_COMMITMENT_MISMATCH for
 * step 6, and nothing derived from it is returned. No warning-and-continue path exists.
 *
 * What this does not do (T-25, T-29, T-36, L-22, L-23): it cannot tell a substituted identity
 * that users never compared by fingerprint from a real one, and it cannot detect a split view
 * created by a legitimate OWNER or ADMIN together with the server; comparing Room Safety Codes
 * can reveal the latter. Raw RKM bytes exist only while a key is created, opened or shared, and
 * are overwritten afterwards (best effort, L-15). Opened keys are non-extractable CryptoKeys.
 */

export interface SignedGenesis extends GenesisStatement {
  readonly signature: Bytes;
}
export interface SignedMembershipGrant extends MembershipGrantStatement {
  readonly signature: Bytes;
}
export interface SignedKeyVersion extends KeyVersionStatement {
  readonly signature: Bytes;
}

/** Everything the server serves for one key version, all of it untrusted until verified here. */
export interface RoomKeyBundle {
  readonly roomId: string;
  readonly genesis: SignedGenesis;
  readonly keyVersion: SignedKeyVersion;
  /** Grants needed for the authority chain and this client's own grant, in any order. */
  readonly grants: readonly SignedMembershipGrant[];
  /** Public identities of every signer named above (current or retired). */
  readonly identities: readonly PublicIdentity[];
  /** This client's own envelope for `keyVersion`. */
  readonly envelope: Bytes;
  /** For a rekeyed version: the commitment of version v-1 that this client verified itself. */
  readonly verifiedPreviousCommitment?: Bytes;
}

/** How this client is authorized to hold the key (step 4). */
export type RecipientAuthorization =
  | { readonly kind: 'recipient-list' }
  | { readonly kind: 'grant'; readonly role: RoomRole; readonly grantor: VerifiedIdentity };

/** A verified room key version, ready for use. Nothing here can be exported as raw key bytes. */
export interface OpenedRoomKey {
  readonly roomId: string;
  readonly keyVersion: number;
  readonly commitment: Bytes;
  /** The verified identity that signed this key version; its fingerprint can be compared out of band. */
  readonly creator: VerifiedIdentity;
  readonly authorization: RecipientAuthorization;
  /** RKM_v as a non-extractable HKDF key (deriveKey, deriveBits). */
  readonly material: Key;
  /** RWK_v: non-extractable AES-256-GCM, wrapKey and unwrapKey only. */
  readonly wrappingKey: Key;
}

/** Limits on untrusted bundle sizes, so a server cannot make a browser verify without bound. */
const MAX_GRANTS = 1_000;
const MAX_IDENTITIES = 500;

const ref = (userId: string, keyId: string): string => `${userId}/${keyId}`;
const selfOf = (vault: UnlockedVault): RecipientRef => ({ userId: vault.identity.userId, keyId: vault.identity.keyId });

const authenticationFailed = (): CryptoError => new CryptoError(CryptoErrorCode.KEY_AUTHENTICATION_FAILED);

function envelopeLabel(roomId: string, keyVersion: number, recipient: RecipientRef): CanonicalBytes {
  return contextBytes('cm.room.envelope', {
    roomId,
    keyVersion,
    recipientUserId: recipient.userId,
    recipientKeyId: recipient.keyId,
    suite: SUITE,
  });
}

function commitmentOf(material: Key, roomId: string, keyVersion: number): Promise<Bytes> {
  return deriveBits(material, contextBytes('cm.room.commitment', { roomId, keyVersion }));
}

function wrappingKeyOf(material: Key, roomId: string, keyVersion: number): Promise<Key> {
  return deriveWrappingKey(material, contextBytes('cm.room.dek-wrap-key', { roomId, keyVersion }));
}

/** Verifies every identity once; identities that fail are left out, so nothing they sign counts. */
async function verifiedIdentities(identities: readonly PublicIdentity[]): Promise<Map<string, VerifiedIdentity>> {
  if (identities.length > MAX_IDENTITIES) throw authenticationFailed();
  const verified = new Map<string, VerifiedIdentity>();
  for (const identity of identities) {
    try {
      const checked = await verifyPublicIdentity(identity);
      verified.set(ref(checked.userId, checked.keyId), checked);
    } catch {
      // An identity that does not verify contributes nothing.
    }
  }
  return verified;
}

/**
 * The authority that follows from the signed genesis statement and the signed grants:
 *   OWNER   the genesis creator, and the subject of an OWNER grant signed by an OWNER;
 *   ADMIN   every OWNER, and the subject of an ADMIN grant signed by an OWNER;
 *   holder  every ADMIN, and the subject of a MEMBER or VIEWER grant signed by an ADMIN or OWNER.
 * Only grants whose signature verifies under the named grantor's identity count. The chain cannot
 * show later demotions or removals: grants are statements, not revocable credentials (L-46).
 */
async function resolveAuthority(
  roomId: string,
  genesisCreator: RecipientRef,
  grants: readonly SignedMembershipGrant[],
  identities: ReadonlyMap<string, VerifiedIdentity>,
) {
  if (grants.length > MAX_GRANTS) throw authenticationFailed();
  const valid: MembershipGrantStatement[] = [];
  for (const grant of grants) {
    const grantor = identities.get(ref(grant.grantorUserId, grant.grantorKeyId));
    if (grantor === undefined) continue;
    let statement: CanonicalBytes;
    try {
      statement = membershipGrantStatement({ ...grant, roomId });
    } catch {
      continue;
    }
    const expected = { userId: grant.grantorUserId, keyId: grant.grantorKeyId };
    if (await verifyStatementBy(grantor, expected, statement, grant.signature)) valid.push(grant);
  }
  const subject = (g: MembershipGrantStatement): string => ref(g.subjectUserId, g.subjectKeyId);
  const grantor = (g: MembershipGrantStatement): string => ref(g.grantorUserId, g.grantorKeyId);
  const owners = new Set([ref(genesisCreator.userId, genesisCreator.keyId)]);
  for (let changed = true; changed;) {
    changed = false;
    for (const g of valid) {
      if (g.role === 'OWNER' && owners.has(grantor(g)) && !owners.has(subject(g))) {
        owners.add(subject(g));
        changed = true;
      }
    }
  }
  const admins = new Set(owners);
  for (const g of valid) if (g.role === 'ADMIN' && owners.has(grantor(g))) admins.add(subject(g));
  const holders = new Set(admins);
  for (const g of valid) {
    if ((g.role === 'MEMBER' || g.role === 'VIEWER') && admins.has(grantor(g))) holders.add(subject(g));
  }
  return {
    isAdmin: (who: RecipientRef): boolean => admins.has(ref(who.userId, who.keyId)),
    /** The strongest verified grant that names `who` and makes it a key holder, if any. */
    grantFor: (who: RecipientRef): MembershipGrantStatement | undefined => {
      const rank = (role: RoomRole): number => ['VIEWER', 'MEMBER', 'ADMIN', 'OWNER'].indexOf(role);
      const named = valid.filter((g) => subject(g) === ref(who.userId, who.keyId));
      const accepted = named.filter((g) =>
        g.role === 'OWNER'
          ? owners.has(grantor(g))
          : g.role === 'ADMIN'
            ? owners.has(grantor(g))
            : admins.has(grantor(g)),
      );
      return accepted.sort((a, b) => rank(b.role) - rank(a.role))[0];
    },
  };
}

interface Verified {
  readonly creator: VerifiedIdentity;
  readonly authorization: RecipientAuthorization;
}

/** Steps 1 to 4 of the verification rule: statements, authority and this client's authorization. */
async function verifyStatements(vault: UnlockedVault, bundle: RoomKeyBundle): Promise<Verified> {
  const { roomId, genesis, keyVersion } = bundle;
  const identities = await verifiedIdentities(bundle.identities);
  const genesisCreator = { userId: genesis.creatorUserId, keyId: genesis.creatorKeyId };
  const genesisSigner = identities.get(ref(genesisCreator.userId, genesisCreator.keyId));
  if (genesisSigner === undefined) throw authenticationFailed();
  // The room ID of every statement is the room being opened, so a statement of another room fails.
  const genesisOk = await verifyStatementBy(
    genesisSigner,
    genesisCreator,
    genesisStatement({ roomId, creatorUserId: genesisCreator.userId, creatorKeyId: genesisCreator.keyId }),
    genesis.signature,
  );
  if (!genesisOk) throw authenticationFailed();

  const creatorRef = { userId: keyVersion.creatorUserId, keyId: keyVersion.creatorKeyId };
  const creator = identities.get(ref(creatorRef.userId, creatorRef.keyId));
  if (creator === undefined) throw authenticationFailed();
  const statement = keyVersionStatement({ ...keyVersion, roomId });
  if (!(await verifyStatementBy(creator, creatorRef, statement, keyVersion.signature))) throw authenticationFailed();

  const authority = await resolveAuthority(roomId, genesisCreator, bundle.grants, identities);
  if (keyVersion.keyVersion === 1) {
    // Version 1 is created with the room, by the room's creator (DF-05).
    if (creatorRef.userId !== genesisCreator.userId || creatorRef.keyId !== genesisCreator.keyId) {
      throw authenticationFailed();
    }
  } else if (!authority.isAdmin(creatorRef)) {
    throw authenticationFailed();
  }
  if (
    keyVersion.keyVersion > 1 &&
    bundle.verifiedPreviousCommitment !== undefined &&
    (keyVersion.previousCommitment === null ||
      !bytesEqual(keyVersion.previousCommitment, bundle.verifiedPreviousCommitment))
  ) {
    throw authenticationFailed();
  }

  const self = selfOf(vault);
  if (keyVersion.recipients.some((r) => r.userId === self.userId && r.keyId === self.keyId)) {
    return { creator, authorization: { kind: 'recipient-list' } };
  }
  const grant = authority.grantFor(self);
  const grantor = grant === undefined ? undefined : identities.get(ref(grant.grantorUserId, grant.grantorKeyId));
  if (grant === undefined || grantor === undefined) throw authenticationFailed();
  return { creator, authorization: { kind: 'grant', role: grant.role, grantor } };
}

/** Steps 5 and 6: opens this client's envelope and checks the key against the signed commitment. */
async function unwrapAndCheck(
  vault: UnlockedVault,
  bundle: RoomKeyBundle,
): Promise<{ readonly raw: Bytes; readonly material: Key }> {
  const { roomId, keyVersion } = bundle;
  const v = keyVersion.keyVersion;
  let raw: Bytes;
  try {
    raw = await unwrap32(vault.encryptionPrivateKey, bundle.envelope, envelopeLabel(roomId, v, selfOf(vault)));
  } catch {
    throw authenticationFailed();
  }
  try {
    const material = await importKeyMaterial(raw.slice());
    const commitment = await commitmentOf(material, roomId, v);
    if (!bytesEqual(commitment, keyVersion.commitment)) {
      throw new CryptoError(CryptoErrorCode.KEY_COMMITMENT_MISMATCH);
    }
    if (keyVersion.previousCommitment !== null) {
      // Reuse check: key material that reproduces the previous commitment is the old key again.
      const underPrevious = await commitmentOf(material, roomId, v - 1);
      if (bytesEqual(underPrevious, keyVersion.previousCommitment)) throw authenticationFailed();
    }
    return { raw, material };
  } catch (error) {
    wipe(raw);
    throw error;
  }
}

/** Maps every failure to the two controlled codes; an unavailable environment stays visible (INV-15). */
function controlled(error: unknown): CryptoError {
  if (isCryptoError(error, CryptoErrorCode.UNAVAILABLE)) return error;
  if (isCryptoError(error, CryptoErrorCode.KEY_COMMITMENT_MISMATCH)) return error;
  return authenticationFailed();
}

async function verifiedRaw(vault: UnlockedVault, bundle: RoomKeyBundle) {
  try {
    const verified = await verifyStatements(vault, bundle);
    const opened = await unwrapAndCheck(vault, bundle);
    return { ...verified, ...opened };
  } catch (error) {
    throw controlled(error);
  }
}

/**
 * Opens one room key version for this client after the full verification rule. The raw key
 * material is wiped before this returns; the result holds only non-extractable keys.
 */
export async function openRoomKey(vault: UnlockedVault, bundle: RoomKeyBundle): Promise<OpenedRoomKey> {
  const { raw, material, creator, authorization } = await verifiedRaw(vault, bundle);
  wipe(raw);
  const { roomId } = bundle;
  const keyVersion = bundle.keyVersion.keyVersion;
  try {
    return {
      roomId,
      keyVersion,
      commitment: bundle.keyVersion.commitment,
      creator,
      authorization,
      material,
      wrappingKey: await wrappingKeyOf(material, roomId, keyVersion),
    };
  } catch (error) {
    throw controlled(error);
  }
}

// ------------------------------------------------------------------------- room creation (DF-05)

/** What POST /rooms carries: public values and ciphertext only, never RKM_1 (INV-01, INV-04). */
export interface RoomCreationKeys {
  readonly creatorKeyId: string;
  readonly commitment: Bytes;
  readonly envelope: Bytes;
  readonly genesisSignature: Bytes;
  readonly keyVersionSignature: Bytes;
}

/**
 * Creates key version 1 of a new room in this browser (CM-T033, DF-05): fresh RKM_1 from the
 * CSPRNG, its commitment, the creator's own envelope, and the signed genesis and key-version
 * statements. RKM_1 is wiped once the envelope exists.
 */
export async function createInitialRoomKey(
  vault: UnlockedVault,
  roomId: string,
): Promise<{ readonly keys: RoomCreationKeys; readonly opened: OpenedRoomKey }> {
  const self = selfOf(vault);
  const rkm = randomBytes(ROOM_KEYS.materialBytes);
  try {
    const material = await importKeyMaterial(rkm.slice());
    const commitment = await commitmentOf(material, roomId, 1);
    const envelope = await wrap32(vault.identity.encryptionPublicKey, rkm, envelopeLabel(roomId, 1, self));
    wipe(rkm);
    const creator = { roomId, creatorUserId: self.userId, creatorKeyId: self.keyId };
    const genesisSignature = await signStatement(vault.signingPrivateKey, genesisStatement(creator));
    const keyVersionSignature = await signStatement(
      vault.signingPrivateKey,
      keyVersionStatement({ ...creator, keyVersion: 1, commitment, previousCommitment: null, recipients: [self] }),
    );
    return {
      keys: { creatorKeyId: self.keyId, commitment, envelope, genesisSignature, keyVersionSignature },
      opened: {
        roomId,
        keyVersion: 1,
        commitment,
        creator: vault.identity,
        authorization: { kind: 'recipient-list' },
        material,
        wrappingKey: await wrappingKeyOf(material, roomId, 1),
      },
    };
  } finally {
    wipe(rkm);
  }
}

// ------------------------------------------------------------------ invitations and grants (DF-06)

/** Signs cm.room.membership-grant for a verified subject identity. */
export async function signMembershipGrant(
  vault: UnlockedVault,
  grant: { readonly roomId: string; readonly subject: VerifiedIdentity; readonly role: RoomRole },
): Promise<{ readonly subjectKeyId: string; readonly signature: Bytes }> {
  const signature = await signStatement(
    vault.signingPrivateKey,
    membershipGrantStatement({
      roomId: grant.roomId,
      subjectUserId: grant.subject.userId,
      subjectKeyId: grant.subject.keyId,
      role: grant.role,
      grantorUserId: vault.identity.userId,
      grantorKeyId: vault.identity.keyId,
    }),
  );
  return { subjectKeyId: grant.subject.keyId, signature };
}

export interface InvitationKeys {
  readonly envelopes: readonly { readonly keyVersion: number; readonly wrappedKey: Bytes }[];
  readonly grantSignature: Bytes;
}

/**
 * Prepares an invitation (CM-T034): every key version to share is verified first with the full
 * rule (a key this browser could not authenticate is never passed on), then wrapped to the
 * invitee's verified identity under a label that names the invitee's user and key, and the
 * membership grant is signed. Raw key material is wiped after each wrap.
 */
export async function createInvitationKeys(
  vault: UnlockedVault,
  input: {
    readonly roomId: string;
    readonly bundles: readonly RoomKeyBundle[];
    readonly invitee: VerifiedIdentity;
    readonly role: RoomRole;
  },
): Promise<InvitationKeys> {
  const versions = input.bundles.map((b) => b.keyVersion.keyVersion);
  if (
    input.bundles.length === 0 ||
    new Set(versions).size !== versions.length ||
    input.bundles.some((b) => b.roomId !== input.roomId)
  ) {
    throw new CryptoError(CryptoErrorCode.INVALID_INPUT);
  }
  const invitee = { userId: input.invitee.userId, keyId: input.invitee.keyId };
  const envelopes: { keyVersion: number; wrappedKey: Bytes }[] = [];
  for (const bundle of input.bundles) {
    const { raw } = await verifiedRaw(vault, bundle);
    try {
      const v = bundle.keyVersion.keyVersion;
      envelopes.push({
        keyVersion: v,
        wrappedKey: await wrap32(input.invitee.encryptionPublicKey, raw, envelopeLabel(input.roomId, v, invitee)),
      });
    } finally {
      wipe(raw);
    }
  }
  const grant = await signMembershipGrant(vault, { roomId: input.roomId, subject: input.invitee, role: input.role });
  return { envelopes, grantSignature: grant.signature };
}

// ---------------------------------------------------------------- Room Safety Code (CP-24, ADR-012)

export interface SafetyCode {
  readonly keyVersion: number;
  /** Six words from the LIB-08 list, most significant first. */
  readonly words: readonly string[];
  /** The same 66 bits as 20 decimal digits (2^66 < 10^20), for an accessible comparison. */
  readonly digits: string;
}

let wordList: readonly string[] | undefined;
function words(): readonly string[] {
  if (wordList === undefined) {
    const list = SAFETY_CODE_WORDS_TEXT.split('\n');
    if (list.length !== 2 ** ROOM_KEYS.safetyCodeBitsPerWord) throw new CryptoError(CryptoErrorCode.UNAVAILABLE);
    wordList = Object.freeze(list);
  }
  return wordList;
}

/** The display form of the first 66 bits of RSC_v. Exported for the known-answer tests only. */
export function safetyCodeFromBits(keyVersion: number, rsc: Bytes): SafetyCode {
  const bitsPerWord = ROOM_KEYS.safetyCodeBitsPerWord;
  const totalBits = bitsPerWord * ROOM_KEYS.safetyCodeWords;
  if (rsc.length < Math.ceil(totalBits / 8)) throw new CryptoError(CryptoErrorCode.INVALID_INPUT);
  let value = BigInt(0);
  for (let i = 0; i < Math.ceil(totalBits / 8); i++) value = (value << BigInt(8)) | BigInt(rsc[i] ?? 0);
  value >>= BigInt(Math.ceil(totalBits / 8) * 8 - totalBits);
  const list = words();
  const mask = BigInt(2 ** bitsPerWord - 1);
  const chosen = Array.from({ length: ROOM_KEYS.safetyCodeWords }, (_, i) => {
    const shift = BigInt(totalBits - bitsPerWord * (i + 1));
    return list[Number((value >> shift) & mask)] ?? '';
  });
  return { keyVersion, words: chosen, digits: value.toString().padStart(ROOM_KEYS.safetyCodeDigits, '0') };
}

/**
 * Computes the Room Safety Code of an opened key version (CP-24): HKDF over the verified key
 * material this browser holds. It is computed only here and is never sent, stored or logged
 * (INV-18). Matching codes show only that two members hold the same key material for this
 * version; they say nothing about who else holds it (L-22).
 */
export async function computeSafetyCode(opened: OpenedRoomKey): Promise<SafetyCode> {
  const rsc = await deriveBits(
    opened.material,
    contextBytes('cm.room.safety-code', { roomId: opened.roomId, keyVersion: opened.keyVersion }),
  );
  try {
    return safetyCodeFromBits(opened.keyVersion, rsc);
  } finally {
    wipe(rsc);
  }
}
