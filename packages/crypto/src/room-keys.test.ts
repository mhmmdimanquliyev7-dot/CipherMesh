describe('room-key envelopes (cm.room.envelope label, T-25, T-07)', () => {
  it('open only for the intended recipient key, room, version and suite', async () => {
    const aliceGrant = await grant(room, owner, alice, 'MEMBER');
    const good = await bundleFor(room, alice, { grants: [aliceGrant] });
    expect((await openRoomKey(alice, good)).keyVersion).toBe(1);
    const wrapped = async (to: RecipientRef, roomId: string, version: number) =>
      wrap32(alice.identity.encryptionPublicKey, room.rkm.slice(), label(roomId, version, to));
    const variants = [
      // the owner's envelope: another private key
      room.ownerEnvelope,
      // labelled for another room, another version, another user or another key of the recipient
      await wrapped(self(alice), randomUUID(), 1),
      await wrapped(self(alice), room.roomId, 2),
      await wrapped({ userId: bob.identity.userId, keyId: alice.identity.keyId }, room.roomId, 1),
      await wrapped({ userId: alice.identity.userId, keyId: bob.identity.keyId }, room.roomId, 1),
      // a label of another purpose (a secret's SEK wrap)
      await wrap32(
        alice.identity.encryptionPublicKey,
        room.rkm.slice(),
        contextBytes('cm.secret.sek-wrap', {
          roomId: room.roomId,
          secretId: room.roomId,
          recipientUserId: alice.identity.userId,
          recipientKeyId: alice.identity.keyId,
          suite: 'CM1',
        }),
      ),
      // a modified ciphertext and malformed sizes
      Uint8Array.from(good.envelope, (b, i) => (i === 200 ? b ^ 1 : b)),
      good.envelope.slice(0, 383),
      new Uint8Array(0),
      new Uint8Array(385),
    ];
    for (const envelope of variants) await refused(openRoomKey(alice, { ...good, envelope }));
  });
});

