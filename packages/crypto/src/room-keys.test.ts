describe('invitation keys (CM-T034)', () => {
  it('wraps every shared version to the invitee only and signs the grant; the invitee opens it', async () => {
    const invitation = await createInvitationKeys(owner, {
      roomId: room.roomId,
      bundles: [await bundleFor(room, owner)],
      invitee: bob.identity,
      role: 'VIEWER',
    });
    expect(invitation.envelopes.map((e) => e.keyVersion)).toEqual([1]);
    const signedGrant: SignedMembershipGrant = {
      roomId: room.roomId,
      subjectUserId: bob.identity.userId,
      subjectKeyId: bob.identity.keyId,
      role: 'VIEWER',
      grantorUserId: owner.identity.userId,
      grantorKeyId: owner.identity.keyId,
      signature: invitation.grantSignature,
    };
    const envelope = invitation.envelopes[0]?.wrappedKey ?? new Uint8Array();
    const base = { ...(await bundleFor(room, bob)), grants: [signedGrant], envelope };
    const opened: OpenedRoomKey = await openRoomKey(bob, base);
    expect(Buffer.from(opened.commitment)).toEqual(Buffer.from(room.v1.commitment));
    // The envelope is bound to Bob's key: Alice's key cannot open it even with a grant of her own.
    await refused(openRoomKey(alice, { ...base, grants: [await grant(room, owner, alice, 'MEMBER')] }));
    // The OpenSSL check of the grant bytes, written out by hand.
    const spki = createPublicKey({ key: Buffer.from(owner.identity.signingKeySpki), format: 'der', type: 'spki' });
    const bytes = json({
      ctx: 'cm.room.membership-grant',
      grantorKeyId: owner.identity.keyId,
      grantorUserId: owner.identity.userId,
      role: 'VIEWER',
      roomId: room.roomId,
      subjectKeyId: bob.identity.keyId,
      subjectUserId: bob.identity.userId,
      v: 1,
    });
    expect(nodeVerify('sha256', bytes, { key: spki, dsaEncoding: 'ieee-p1363' }, invitation.grantSignature)).toBe(true);
    expect(Buffer.from(membershipGrantStatement(signedGrant))).toEqual(bytes);
  });

  it('never passes on a key it could not authenticate, and refuses inconsistent input', async () => {
    const tampered = { ...(await bundleFor(room, owner)), keyVersion: { ...room.v1, signature: new Uint8Array(64) } };
    await refused(
      createInvitationKeys(owner, { roomId: room.roomId, bundles: [tampered], invitee: bob.identity, role: 'MEMBER' }),
    );
    const good = await bundleFor(room, owner);
    for (const bundles of [[], [good, good], [{ ...good, roomId: randomUUID() }]]) {
      await rejects(
        createInvitationKeys(owner, { roomId: room.roomId, bundles, invitee: bob.identity, role: 'MEMBER' }),
        CryptoErrorCode.INVALID_INPUT,
      );
    }
  });
});

// ------------------------------------------------------------------- Room Safety Code (CP-24)

describe('Room Safety Code (CM-T085, CP-24, ADR-012)', () => {
  it('uses the pinned LIB-08 word list (BIP-39 English, checksum of the upstream file)', () => {
    const words = SAFETY_CODE_WORDS_TEXT.split('\n');
    expect(words).toHaveLength(2048);
    expect(new Set(words).size).toBe(2048);
    expect(createHash('sha256').update(`${SAFETY_CODE_WORDS_TEXT}\n`).digest('hex')).toBe(SAFETY_CODE_WORDS_SHA256);
    expect([words[0], words[1], words[2047]]).toEqual(['abandon', 'ability', 'zoo']);
  });

  it('maps the first 66 bits to six 11-bit word indices, most significant first (known answers)', () => {
    expect(safetyCodeFromBits(1, new Uint8Array(32))).toEqual({
      keyVersion: 1,
      words: ['abandon', 'abandon', 'abandon', 'abandon', 'abandon', 'abandon'],
      digits: '00000000000000000000',
    });
    expect(safetyCodeFromBits(3, new Uint8Array(32).fill(0xff))).toEqual({
      keyVersion: 3,
      words: ['zoo', 'zoo', 'zoo', 'zoo', 'zoo', 'zoo'],
      digits: '73786976294838206463',
    });
    // Indices 1, 2, 3, 4, 5, 2047: 00000000001 00000000010 00000000011 00000000100 00000000101 11111111111
    const pattern = BigInt(
      '0b' + ['00000000001', '00000000010', '00000000011', '00000000100', '00000000101', '11111111111'].join(''),
    );
    const bytes = Buffer.alloc(32);
    bytes.writeBigUInt64BE(pattern >> BigInt(2), 0);
    bytes[8] = Number((pattern & BigInt(3)) << BigInt(6));
    expect(safetyCodeFromBits(1, new Uint8Array(bytes)).words).toEqual([
      'ability',
      'able',
      'about',
      'above',
      'absent',
      'zoo',
    ]);
    expect(safetyCodeFromBits(1, new Uint8Array(bytes)).digits).toBe(pattern.toString().padStart(20, '0'));
    expect(() => safetyCodeFromBits(1, new Uint8Array(8))).toThrow();
  });

  it('derives RSC_v with HKDF exactly as CP-24 specifies (known-answer vector, OpenSSL cross-check)', async () => {
    const rkm = Uint8Array.from({ length: 32 }, (_, i) => i);
    const roomId = '0f3e2d1c-4b5a-4968-8776-a5b4c3d2e1f0';
    const opened = { roomId, keyVersion: 1, material: await importKeyMaterial(rkm.slice()) } as OpenedRoomKey;
    const code = await computeSafetyCode(opened);
    const info = json({ ctx: 'cm.room.safety-code', keyVersion: 1, roomId, v: 1 });
    const rsc = new Uint8Array(hkdfSync('sha256', rkm, ZERO_SALT, info, 32));
    expect(code).toEqual(safetyCodeFromBits(1, rsc));
    // Pinned vector, repeated in the browser engines by tests/e2e/room-crypto.spec.ts.
    expect(code).toEqual(SAFETY_CODE_VECTOR);
  });

  it('is the same for every holder of the same key, and changes with the key, the version and the room', async () => {
    const forOwner = await computeSafetyCode(await openRoomKey(owner, await bundleFor(room, owner)));
    const forAlice = await computeSafetyCode(
      await openRoomKey(alice, await bundleFor(room, alice, { grants: [await grant(room, owner, alice, 'MEMBER')] })),
    );
    expect(forAlice).toEqual(forOwner);
    const material = await importKeyMaterial(room.rkm.slice());
    const sameKey = (roomId: string, keyVersion: number) =>
      computeSafetyCode({ roomId, keyVersion, material } as OpenedRoomKey);
    expect(await sameKey(room.roomId, 1)).toEqual(forOwner);
    expect((await sameKey(room.roomId, 2)).words).not.toEqual(forOwner.words);
    expect((await sameKey(randomUUID(), 1)).words).not.toEqual(forOwner.words);
    const otherRoom = await newRoom(owner);
    const other = await computeSafetyCode(await openRoomKey(owner, await bundleFor(otherRoom, owner)));
    expect(other.words).not.toEqual(forOwner.words);
  });
});

