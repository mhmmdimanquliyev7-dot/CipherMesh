// Phase 6 (CM-T033, CM-T034, CM-T036, CM-T085): room key creation, the ADR-015 section 4
// verification rule including the `key-injection` suite (T-36), envelope binding (T-25, T-07),
// commitment checks (T-29) and the Room Safety Code (CP-24). Identities are generated by the real
// package code; nothing here is a fixed key. Independent cross-checks use Node.js crypto (OpenSSL):
// HKDF for the commitment and the Safety Code, ECDSA verification of the signed statements, and
// RSA-OAEP decryption with a label written out by hand.

const ZERO_SALT = Buffer.alloc(32);
const json = (value: unknown): Buffer => Buffer.from(JSON.stringify(value), 'utf8');

/** An unlocked vault for a generated identity (the vault wrapping itself is tested in vault.test.ts). */
async function member(): Promise<UnlockedVault> {
  const generated = await generateIdentity(randomUUID());
  return {
    identity: generated.identity,
    encryptionPrivateKey: generated.encryptionPrivateKey,
    signingPrivateKey: generated.signingPrivateKey,
  };
}

const self = (v: UnlockedVault): RecipientRef => ({ userId: v.identity.userId, keyId: v.identity.keyId });
const publicOf = (v: UnlockedVault | VerifiedIdentity): PublicIdentity => {
  const identity = 'identity' in v ? v.identity : v;
  return {
    userId: identity.userId,
    keyId: identity.keyId,
    suite: identity.suite,
    encryptionKeySpki: identity.encryptionKeySpki,
    signingKeySpki: identity.signingKeySpki,
    bindingSignature: identity.bindingSignature,
    fingerprint: identity.fingerprint,
  };
};

const label = (roomId: string, keyVersion: number, to: RecipientRef) =>
  contextBytes('cm.room.envelope', {
    roomId,
    keyVersion,
    recipientUserId: to.userId,
    recipientKeyId: to.keyId,
    suite: 'CM1',
  });

async function rejects(promise: Promise<unknown>, code: string): Promise<void> {
  let caught: unknown;
  try {
    await promise;
  } catch (error) {
    caught = error;
  }
  expect(isCryptoError(caught), String(caught)).toBe(true);
  expect((caught as { code: string }).code).toBe(code);
}
const refused = (promise: Promise<unknown>) => rejects(promise, CryptoErrorCode.KEY_AUTHENTICATION_FAILED);

/** A room created by `owner`, as the server would store and serve it. */
interface Room {
  readonly roomId: string;
  readonly owner: UnlockedVault;
  readonly genesis: RoomKeyBundle['genesis'];
  readonly v1: RoomKeyBundle['keyVersion'];
  readonly ownerEnvelope: Bytes;
  /** RKM_1, recovered here only to build test variants (the package never returns it). */
  readonly rkm: Bytes;
}

async function newRoom(owner: UnlockedVault): Promise<Room> {
  const roomId = randomUUID();
  const { keys } = await createInitialRoomKey(owner, roomId);
  const rkm = await rsaOaepDecryptRaw(owner.encryptionPrivateKey, keys.envelope, label(roomId, 1, self(owner)));
  return {
    roomId,
    owner,
    genesis: {
      roomId,
      creatorUserId: owner.identity.userId,
      creatorKeyId: owner.identity.keyId,
      signature: keys.genesisSignature,
    },
    v1: {
      roomId,
      keyVersion: 1,
      commitment: keys.commitment,
      previousCommitment: null,
      creatorUserId: owner.identity.userId,
      creatorKeyId: owner.identity.keyId,
      recipients: [self(owner)],
      signature: keys.keyVersionSignature,
    },
    ownerEnvelope: keys.envelope,
    rkm,
  };
}

async function grant(
  room: Room,
  grantor: UnlockedVault,
  subject: UnlockedVault,
  role: 'OWNER' | 'ADMIN' | 'MEMBER' | 'VIEWER',
): Promise<SignedMembershipGrant> {
  const signed = await signMembershipGrant(grantor, { roomId: room.roomId, subject: subject.identity, role });
  return {
    roomId: room.roomId,
    subjectUserId: subject.identity.userId,
    subjectKeyId: subject.identity.keyId,
    role,
    grantorUserId: grantor.identity.userId,
    grantorKeyId: grantor.identity.keyId,
    signature: signed.signature,
  };
}

/** The bundle a member fetches for version 1 of the room, with an envelope for that member. */
async function bundleFor(
  room: Room,
  to: UnlockedVault,
  extra: { grants?: SignedMembershipGrant[]; identities?: UnlockedVault[] } = {},
): Promise<RoomKeyBundle> {
  const envelope =
    to === room.owner
      ? room.ownerEnvelope
      : await wrap32(to.identity.encryptionPublicKey, room.rkm.slice(), label(room.roomId, 1, self(to)));
  return {
    roomId: room.roomId,
    genesis: room.genesis,
    keyVersion: room.v1,
    grants: extra.grants ?? [],
    identities: [room.owner, ...(extra.identities ?? [])].map(publicOf),
    envelope,
  };
}

/** Signs a key version as `creator` (for synthetic rekeyed versions and forged variants). */
async function signedVersion(
  room: Room,
  creator: UnlockedVault,
  fields: { keyVersion: number; rkm: Bytes; previousCommitment: Bytes | null; recipients: RecipientRef[] },
): Promise<RoomKeyBundle['keyVersion']> {
  const commitment = new Uint8Array(
    hkdfSync(
      'sha256',
      fields.rkm,
      ZERO_SALT,
      contextBytes('cm.room.commitment', { roomId: room.roomId, keyVersion: fields.keyVersion }),
      32,
    ),
  );
  const statement = {
    roomId: room.roomId,
    keyVersion: fields.keyVersion,
    commitment,
    previousCommitment: fields.previousCommitment,
    creatorUserId: creator.identity.userId,
    creatorKeyId: creator.identity.keyId,
    recipients: sortRecipients(fields.recipients),
  };
  return { ...statement, signature: await signStatement(creator.signingPrivateKey, keyVersionStatement(statement)) };
}

let owner: UnlockedVault;
let admin: UnlockedVault;
let alice: UnlockedVault;
let bob: UnlockedVault;
let outsider: UnlockedVault;
let room: Room;

beforeAll(async () => {
  [owner, admin, alice, bob, outsider] = await Promise.all([member(), member(), member(), member(), member()]);
  room = await newRoom(owner);
}, 120_000);

// ------------------------------------------------------------------------------- creation (DF-05)

describe('initial room key version (CM-T033, DF-05)', () => {
  it('commits to fresh random key material with HKDF exactly as CP-03 specifies (OpenSSL cross-check)', async () => {
    const roomId = randomUUID();
    const { keys } = await createInitialRoomKey(owner, roomId);
    expect(keys.creatorKeyId).toBe(owner.identity.keyId);
    expect(keys.commitment).toHaveLength(32);
    expect(keys.envelope).toHaveLength(384);
    expect(keys.genesisSignature).toHaveLength(64);
    expect(keys.keyVersionSignature).toHaveLength(64);
    // The label is written out by hand here, independently of the context builder.
    const handLabel = json({
      ctx: 'cm.room.envelope',
      keyVersion: 1,
      recipientKeyId: owner.identity.keyId,
      recipientUserId: owner.identity.userId,
      roomId,
      suite: 'CM1',
      v: 1,
    });
    const rkm = await rsaOaepDecryptRaw(owner.encryptionPrivateKey, keys.envelope, new Uint8Array(handLabel));
    expect(rkm).toHaveLength(32);
    const info = json({ ctx: 'cm.room.commitment', keyVersion: 1, roomId, v: 1 });
    expect(Buffer.from(keys.commitment)).toEqual(Buffer.from(hkdfSync('sha256', rkm, ZERO_SALT, info, 32)));
    // Nothing that crosses the network contains the key material.
    for (const value of [keys.commitment, keys.envelope, keys.genesisSignature, keys.keyVersionSignature]) {
      expect(Buffer.from(value).includes(Buffer.from(rkm))).toBe(false);
    }
  });

  it('signs the genesis and version-1 statements so that OpenSSL verifies the hand-written bytes', async () => {
    const roomId = randomUUID();
    const { keys } = await createInitialRoomKey(owner, roomId);
    const spki = createPublicKey({ key: Buffer.from(owner.identity.signingKeySpki), format: 'der', type: 'spki' });
    const ecdsa = { key: spki, dsaEncoding: 'ieee-p1363' as const };
    const ids = { creatorKeyId: owner.identity.keyId, creatorUserId: owner.identity.userId };
    // Members in RFC 8785 order: creatorKeyId, creatorUserId, ctx, roomId, suite, v.
    const genesis = json({ ...ids, ctx: 'cm.room.genesis', roomId, suite: 'CM1', v: 1 });
    expect(nodeVerify('sha256', genesis, ecdsa, keys.genesisSignature)).toBe(true);
    const version = json({
      commitment: Buffer.from(keys.commitment).toString('base64url'),
      ...ids,
      ctx: 'cm.room.key-version',
      keyVersion: 1,
      previousCommitment: null,
      recipients: [{ keyId: owner.identity.keyId, userId: owner.identity.userId }],
      roomId,
      suite: 'CM1',
      v: 1,
    });
    expect(nodeVerify('sha256', version, ecdsa, keys.keyVersionSignature)).toBe(true);
  });

  it('uses new key material for every room (CSPRNG, CP-23)', async () => {
    const roomId = randomUUID();
    const [a, b] = await Promise.all([createInitialRoomKey(owner, roomId), createInitialRoomKey(owner, roomId)]);
    expect(Buffer.from(a.keys.commitment)).not.toEqual(Buffer.from(b.keys.commitment));
    expect(Buffer.from(a.keys.envelope)).not.toEqual(Buffer.from(b.keys.envelope));
  });

  it('returns only non-extractable keys with the minimum usages', async () => {
    const { opened } = await createInitialRoomKey(owner, randomUUID());
    expect(opened.material.extractable).toBe(false);
    expect([...opened.material.usages].sort()).toEqual(['deriveBits', 'deriveKey']);
    expect(opened.wrappingKey.extractable).toBe(false);
    expect([...opened.wrappingKey.usages].sort()).toEqual(['unwrapKey', 'wrapKey']);
    expect(opened.authorization).toEqual({ kind: 'recipient-list' });
  });

  it('the creator reopens version 1 from what the server stores, with the same commitment', async () => {
    const opened = await openRoomKey(owner, await bundleFor(room, owner));
    expect(opened.keyVersion).toBe(1);
    expect(Buffer.from(opened.commitment)).toEqual(Buffer.from(room.v1.commitment));
    expect(opened.creator.fingerprint).toBe(owner.identity.fingerprint);
    expect(opened.authorization).toEqual({ kind: 'recipient-list' });
  });
});

// ------------------------------------------------------- the verification rule and key injection

describe('verification rule (ADR-015 section 4) and the key-injection suite (CM-T036, T-36)', () => {
  it('an invited MEMBER is authorized by a grant signed by the OWNER (Phase 6 clarification)', async () => {
    const opened = await openRoomKey(
      alice,
      await bundleFor(room, alice, { grants: [await grant(room, owner, alice, 'MEMBER')] }),
    );
    expect(opened.authorization).toMatchObject({ kind: 'grant', role: 'MEMBER' });
    expect(opened.authorization.kind === 'grant' && opened.authorization.grantor.keyId).toBe(owner.identity.keyId);
  });

  it('a member invited by an ADMIN needs the ADMIN grant signed by the OWNER (authority chain)', async () => {
    const adminGrant = await grant(room, owner, admin, 'ADMIN');
    const aliceGrant = await grant(room, admin, alice, 'VIEWER');
    const bundle = await bundleFor(room, alice, { grants: [aliceGrant, adminGrant], identities: [admin] });
    expect((await openRoomKey(alice, bundle)).authorization).toMatchObject({ kind: 'grant', role: 'VIEWER' });
    // Without the ADMIN's own grant the chain is broken.
    await refused(openRoomKey(alice, { ...bundle, grants: [aliceGrant] }));
    // An ADMIN grant signed by another ADMIN confers nothing: only the OWNER grants ADMIN.
    const selfMadeAdmin = await grant(room, admin, bob, 'ADMIN');
    const viaBob = await grant(room, bob, alice, 'MEMBER');
    await refused(
      openRoomKey(alice, {
        ...bundle,
        grants: [adminGrant, selfMadeAdmin, viaBob],
        identities: [owner, admin, bob].map(publicOf),
      }),
    );
  });

  it('ownership transferred by a signed OWNER grant carries OWNER authority', async () => {
    const toAdmin = await grant(room, owner, admin, 'OWNER');
    const adminInvitesAdmin = await grant(room, admin, bob, 'ADMIN');
    const bundle = await bundleFor(room, bob, { grants: [toAdmin, adminInvitesAdmin], identities: [admin] });
    expect((await openRoomKey(bob, bundle)).authorization).toMatchObject({ kind: 'grant', role: 'ADMIN' });
  });

  it('refuses a missing recipient: neither in the signed list nor granted', async () => {
    await refused(openRoomKey(alice, await bundleFor(room, alice)));
  });

  it('refuses grants by people without authority, for another key or for another room', async () => {
    const memberGrant = await grant(room, owner, alice, 'MEMBER');
    // A MEMBER cannot let someone else in.
    const byMember = await grant(room, alice, bob, 'MEMBER');
    await refused(
      openRoomKey(bob, await bundleFor(room, bob, { grants: [memberGrant, byMember], identities: [alice] })),
    );
    // A grant for another identity key of the same user (for example before a vault reset).
    const other = await member();
    const stale = { ...(await grant(room, owner, alice, 'MEMBER')), subjectKeyId: other.identity.keyId };
    await refused(openRoomKey(alice, await bundleFor(room, alice, { grants: [stale] })));
    // A grant signed for room B does not verify in room A.
    const roomB = await newRoom(owner);
    const elsewhere = { ...(await grant(roomB, owner, alice, 'MEMBER')), roomId: room.roomId };
    await refused(openRoomKey(alice, await bundleFor(room, alice, { grants: [elsewhere] })));
    // A grant whose role was raised after signing.
    const raised = { ...memberGrant, role: 'ADMIN' as const };
    const fine = await openRoomKey(alice, await bundleFor(room, alice, { grants: [raised, memberGrant] }));
    expect(fine.authorization).toMatchObject({ role: 'MEMBER' });
    await refused(openRoomKey(alice, await bundleFor(room, alice, { grants: [raised] })));
  });

  it('refuses unsigned, forged and malformed key-version signatures', async () => {
    const bundle = await bundleFor(room, owner);
    for (const signature of [
      new Uint8Array(64),
      Uint8Array.from(room.v1.signature, (b, i) => (i === 10 ? b ^ 1 : b)),
      room.v1.signature.slice(0, 63),
      new Uint8Array(0),
      room.genesis.signature,
    ]) {
      await refused(openRoomKey(owner, { ...bundle, keyVersion: { ...room.v1, signature } }));
    }
  });

  it('refuses a key version signed by another key than the one it names (wrongly attributed)', async () => {
    const bundle = await bundleFor(room, owner);
    const forged = await signStatement(outsider.signingPrivateKey, keyVersionStatement(room.v1));
    await refused(
      openRoomKey(owner, {
        ...bundle,
        keyVersion: { ...room.v1, signature: forged },
        identities: [owner, outsider].map(publicOf),
      }),
    );
    // Attributed to the outsider and signed by it: valid signature, but no authority (T-36).
    const injected = await signedVersion(room, outsider, {
      keyVersion: 1,
      rkm: room.rkm,
      previousCommitment: null,
      recipients: [self(owner)],
    });
    await refused(openRoomKey(owner, { ...bundle, keyVersion: injected, identities: [owner, outsider].map(publicOf) }));
  });

  it('refuses a server-made key version even when every member gets a matching envelope (T-36)', async () => {
    // The server knows only public keys: it can choose key material, commit to it and wrap it to
    // everyone, but it cannot sign as an authorized member.
    const attackerKey = new Uint8Array(32).fill(0x42);
    const injected = await signedVersion(room, outsider, {
      keyVersion: 1,
      rkm: attackerKey,
      previousCommitment: null,
      recipients: [self(owner)],
    });
    const envelope = await wrap32(
      owner.identity.encryptionPublicKey,
      attackerKey.slice(),
      label(room.roomId, 1, self(owner)),
    );
    await refused(
      openRoomKey(owner, {
        ...(await bundleFor(room, owner)),
        keyVersion: injected,
        envelope,
        identities: [owner, outsider].map(publicOf),
      }),
    );
  });

  it('refuses every modified field of the signed key-version statement', async () => {
    const bundle = await bundleFor(room, owner);
    const flipped = Uint8Array.from(room.v1.commitment, (b, i) => (i === 0 ? b ^ 0x80 : b));
    for (const keyVersion of [
      { ...room.v1, commitment: flipped },
      { ...room.v1, keyVersion: 2, previousCommitment: room.v1.commitment },
      { ...room.v1, recipients: sortRecipients([self(owner), self(outsider)]) },
      { ...room.v1, recipients: [self(outsider)] },
      { ...room.v1, creatorUserId: outsider.identity.userId },
    ]) {
      await refused(openRoomKey(owner, { ...bundle, keyVersion }));
    }
    // Recipient order is part of the canonical form: an unsorted list never verifies.
    const two = await signedVersion(room, owner, {
      keyVersion: 1,
      rkm: room.rkm,
      previousCommitment: null,
      recipients: [self(owner), self(alice)],
    });
    expect((await openRoomKey(owner, { ...bundle, keyVersion: two })).keyVersion).toBe(1);
    await refused(openRoomKey(owner, { ...bundle, keyVersion: { ...two, recipients: [...two.recipients].reverse() } }));
  });

  it('refuses a statement signed with a different suite or for another room', async () => {
    const bundle = await bundleFor(room, owner);
    const fields = {
      commitment: Buffer.from(room.v1.commitment).toString('base64url'),
      creatorKeyId: owner.identity.keyId,
      creatorUserId: owner.identity.userId,
      ctx: 'cm.room.key-version',
      keyVersion: 1,
      previousCommitment: null,
      recipients: [{ keyId: owner.identity.keyId, userId: owner.identity.userId }],
      roomId: room.roomId,
      suite: 'CM2',
      v: 1,
    };
    const otherSuite = await signStatement(owner.signingPrivateKey, canonicalBytes(fields) as never);
    await refused(openRoomKey(owner, { ...bundle, keyVersion: { ...room.v1, signature: otherSuite } }));
    // Statements of room B served as room A: every statement names its room.
    const roomB = await newRoom(owner);
    const bundleB = await bundleFor(roomB, owner);
    await refused(openRoomKey(owner, { ...bundleB, roomId: room.roomId }));
    await refused(
      openRoomKey(owner, { ...bundle, genesis: roomB.genesis, keyVersion: roomB.v1, envelope: roomB.ownerEnvelope }),
    );
  });

  it('refuses a forged, foreign or missing genesis statement and a tampered identity', async () => {
    const bundle = await bundleFor(room, owner);
    await refused(openRoomKey(owner, { ...bundle, genesis: { ...room.genesis, signature: new Uint8Array(64) } }));
    const foreign = await signStatement(
      owner.signingPrivateKey,
      genesisStatement({ ...room.genesis, roomId: randomUUID() }),
    );
    await refused(openRoomKey(owner, { ...bundle, genesis: { ...room.genesis, signature: foreign } }));
    await refused(openRoomKey(owner, { ...bundle, identities: [] }));
    const tampered = { ...publicOf(owner), fingerprint: 'f'.repeat(64) };
    await refused(openRoomKey(owner, { ...bundle, identities: [tampered] }));
  });

  it('refuses a version 1 created by anyone but the room creator, and a rekeyed version by a MEMBER', async () => {
    const adminGrant = await grant(room, owner, admin, 'ADMIN');
    const v1ByAdmin = await signedVersion(room, admin, {
      keyVersion: 1,
      rkm: room.rkm,
      previousCommitment: null,
      recipients: [self(owner)],
    });
    await refused(
      openRoomKey(owner, {
        ...(await bundleFor(room, owner, { grants: [adminGrant], identities: [admin] })),
        keyVersion: v1ByAdmin,
      }),
    );
    // Synthetic version 2 (the rekey itself is Phase 11): signed by an ADMIN it verifies...
    const rkm2 = new Uint8Array(32).fill(7);
    const v2 = await signedVersion(room, admin, {
      keyVersion: 2,
      rkm: rkm2,
      previousCommitment: room.v1.commitment,
      recipients: [self(owner)],
    });
    const env2 = await wrap32(owner.identity.encryptionPublicKey, rkm2.slice(), label(room.roomId, 2, self(owner)));
    const base = {
      ...(await bundleFor(room, owner, { grants: [adminGrant], identities: [admin, alice] })),
      keyVersion: v2,
      envelope: env2,
    };
    expect((await openRoomKey(owner, { ...base, verifiedPreviousCommitment: room.v1.commitment })).keyVersion).toBe(2);
    // ...but not when the previous commitment differs from the one this client verified (fork),
    await refused(openRoomKey(owner, { ...base, verifiedPreviousCommitment: new Uint8Array(32) }));
    // ...and not when a MEMBER signs it.
    const aliceGrant = await grant(room, owner, alice, 'MEMBER');
    const v2ByMember = await signedVersion(room, alice, {
      keyVersion: 2,
      rkm: rkm2,
      previousCommitment: room.v1.commitment,
      recipients: [self(owner)],
    });
    await refused(openRoomKey(owner, { ...base, grants: [adminGrant, aliceGrant], keyVersion: v2ByMember }));
  });

  it('refuses a rekeyed version that reuses the previous key material (reuse check)', async () => {
    const adminGrant = await grant(room, owner, admin, 'ADMIN');
    const reused = await signedVersion(room, admin, {
      keyVersion: 2,
      rkm: room.rkm,
      previousCommitment: room.v1.commitment,
      recipients: [self(owner)],
    });
    const envelope = await wrap32(
      owner.identity.encryptionPublicKey,
      room.rkm.slice(),
      label(room.roomId, 2, self(owner)),
    );
    await refused(
      openRoomKey(owner, {
        ...(await bundleFor(room, owner, { grants: [adminGrant], identities: [admin] })),
        keyVersion: reused,
        envelope,
      }),
    );
  });

  it('refuses a key that does not match the signed commitment with KEY_COMMITMENT_MISMATCH (T-29)', async () => {
    // A malicious member wraps different key material for one recipient while the server is honest.
    const other = new Uint8Array(32).fill(9);
    const envelope = await wrap32(
      alice.identity.encryptionPublicKey,
      other.slice(),
      label(room.roomId, 1, self(alice)),
    );
    const bundle = {
      ...(await bundleFor(room, alice, { grants: [await grant(room, owner, alice, 'MEMBER')] })),
      envelope,
    };
    await rejects(openRoomKey(alice, bundle), CryptoErrorCode.KEY_COMMITMENT_MISMATCH);
  });

  it('refuses oversized bundles before verifying them (bounded work)', async () => {
    const bundle = await bundleFor(room, owner);
    await refused(openRoomKey(owner, { ...bundle, identities: Array.from({ length: 501 }, () => publicOf(owner)) }));
    const g = await grant(room, owner, alice, 'MEMBER');
    await refused(openRoomKey(owner, { ...bundle, grants: Array.from({ length: 1_001 }, () => g) }));
  });

  it('documents the limit: an authorized OWNER colluding with the server can split the room; only Safety Codes reveal it', async () => {
    // CM-T036 and CM-T085: both members' checks pass, because each version is validly signed by the
    // OWNER and each envelope matches its own signed commitment. The commitment check cannot see
    // the split view; the Room Safety Codes differ, which members notice only if they compare.
    const otherKey = new Uint8Array(32).fill(0x5a);
    const split = await signedVersion(room, owner, {
      keyVersion: 1,
      rkm: otherKey,
      previousCommitment: null,
      recipients: [self(owner)],
    });
    const aliceGrant = await grant(room, owner, alice, 'MEMBER');
    const bobGrant = await grant(room, owner, bob, 'MEMBER');
    const forAlice = await openRoomKey(alice, await bundleFor(room, alice, { grants: [aliceGrant] }));
    const bobEnvelope = await wrap32(
      bob.identity.encryptionPublicKey,
      otherKey.slice(),
      label(room.roomId, 1, self(bob)),
    );
    const forBob = await openRoomKey(bob, {
      ...(await bundleFor(room, bob, { grants: [bobGrant] })),
      keyVersion: split,
      envelope: bobEnvelope,
    });
    expect(Buffer.from(forAlice.commitment)).not.toEqual(Buffer.from(forBob.commitment));
    expect((await computeSafetyCode(forAlice)).words).not.toEqual((await computeSafetyCode(forBob)).words);
  });

  it('documents the limit: a substituted creator identity verifies; only fingerprint comparison reveals it (T-25)', async () => {
    // A server that invents an identity under the OWNER's user ID can sign a whole room of its own.
    // The binding signature is self-signed, so the checks pass; the fingerprint shown to members
    // differs from the real OWNER's, which people see only when they compare it (L-07, L-18).
    const impostor = await generateIdentity(owner.identity.userId);
    const fake: UnlockedVault = {
      identity: impostor.identity,
      encryptionPrivateKey: impostor.encryptionPrivateKey,
      signingPrivateKey: impostor.signingPrivateKey,
    };
    const fakeRoom = await newRoom(fake);
    const opened = await openRoomKey(fake, await bundleFor(fakeRoom, fake));
    expect(opened.creator.userId).toBe(owner.identity.userId);
    expect(opened.creator.fingerprint).not.toBe(owner.identity.fingerprint);
  });
});

