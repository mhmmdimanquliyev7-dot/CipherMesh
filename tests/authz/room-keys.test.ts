// Phase 6, CM-T033 and the server side of CM-T036: room creation with key version 1, the signed
// statements the API verifies before storing anything, what the API serves members to verify
// themselves, and the browser's refusal of keys a server-side attacker wrote (T-36, T-29). Real
// identities generated by packages/crypto, the real API and PostgreSQL as cm_api; nothing in the
// verification path is mocked.
let api: AuthTestApi;
let db: pg.Client;

beforeAll(async () => {
  loadDatabaseTestEnv();
  api = await startAuthApi();
  db = await testDatabase(inject('databaseName')).connect('api');
});
afterAll(async () => {
  await api.close();
  await db.end();
});

const create = (who: Person, body: Record<string, unknown>) => who.browser.request('POST', '/rooms', body);
const b64 = (bytes: Uint8Array): string => Buffer.from(bytes).toString('base64url');

async function stored(roomId: string) {
  const { rows } = await db.query<{ rooms: number; members: number; versions: number; envelopes: number }>(
    `SELECT (SELECT count(*)::int FROM rooms WHERE id = $1) AS rooms,
            (SELECT count(*)::int FROM room_members WHERE room_id = $1) AS members,
            (SELECT count(*)::int FROM room_key_versions WHERE room_id = $1) AS versions,
            (SELECT count(*)::int FROM key_envelopes WHERE room_id = $1) AS envelopes`,
    [roomId],
  );
  return rows[0];
}

/** RKM_1 of a room, recovered from the owner's envelope with the owner's private key (test only). */
async function roomKeyMaterial(owner: Person, roomId: string): Promise<Buffer> {
  const vault = vaultOf(owner);
  const { envelopes } = await fetchKeyMaterial(owner, roomId);
  const envelope = Buffer.from(envelopes[0]?.wrappedKey ?? '', 'base64url');
  const label = contextBytes('cm.room.envelope', {
    roomId,
    keyVersion: 1,
    recipientUserId: vault.identity.userId,
    recipientKeyId: vault.identity.keyId,
    suite: 'CM1',
  });
  return Buffer.from(await rsaOaepDecryptRaw(vault.encryptionPrivateKey, new Uint8Array(envelope), label));
}

describe('room creation with key version 1 (CM-T033, DF-05)', () => {
  it('refuses unsigned, wrongly signed and wrongly attributed statements, storing nothing', async () => {
    const owner = await personWithVault(api, db);
    const other = await personWithVault(api, db);
    const vault = vaultOf(owner);
    for (const [label, mutate] of [
      [
        'filler signatures',
        (k: Record<string, string>) => ({
          ...k,
          genesisSignature: b64(randomBytes(64)),
          keyVersionSignature: b64(randomBytes(64)),
        }),
      ],
      [
        'a genesis signature of another room',
        async (k: Record<string, string>) => ({
          ...k,
          genesisSignature: b64(
            await signStatement(
              vault.signingPrivateKey,
              genesisStatement({
                roomId: randomUUID(),
                creatorUserId: owner.userId,
                creatorKeyId: vault.identity.keyId,
              }),
            ),
          ),
        }),
      ],
      [
        'a key-version signature over another commitment',
        (k: Record<string, string>) => ({ ...k, commitment: b64(randomBytes(32)) }),
      ],
    ] as const) {
      const roomId = randomUUID();
      const body = await creationBody(owner, roomId);
      const keys = await mutate(body['keys'] as Record<string, string>);
      api.events.length = 0;
      const response = await create(owner, { ...body, keys });
      expect(response.status, label).toBe(422);
      expect(errorCode(response), label).toBe('ROOM_STATEMENT_INVALID');
      expect(await stored(roomId), label).toEqual({ rooms: 0, members: 0, versions: 0, envelopes: 0 });
      expect(api.events.find((e) => e.name === 'ROOM_STATEMENT_REJECTED')?.details).toEqual({
        roomId,
        statement: 'GENESIS_AND_KEY_VERSION',
      });
    }
    // Validly signed, but by someone else for the same room: the creator's identity must sign.
    const roomId = randomUUID();
    const othersBody = await creationBody(other, roomId);
    const response = await create(owner, othersBody);
    expect(response.status).toBe(409);
    expect(errorCode(response)).toBe('IDENTITY_KEY_CHANGED');
    expect(await stored(roomId)).toEqual({ rooms: 0, members: 0, versions: 0, envelopes: 0 });
  });

  it('signs a recipient list of exactly the creator: a list naming others is refused', async () => {
    const owner = await personWithVault(api, db);
    const outsider = await personWithVault(api, db);
    const vault = vaultOf(owner);
    const roomId = randomUUID();
    const body = await creationBody(owner, roomId);
    const keys = body['keys'] as Record<string, string>;
    const recipients = [
      { userId: owner.userId, keyId: vault.identity.keyId },
      { userId: outsider.userId, keyId: vaultOf(outsider).identity.keyId },
    ].sort((a, b) => (a.userId < b.userId ? -1 : 1));
    const signature = await signStatement(
      vault.signingPrivateKey,
      keyVersionStatement({
        roomId,
        keyVersion: 1,
        commitment: new Uint8Array(Buffer.from(keys['commitment'] ?? '', 'base64url')),
        previousCommitment: null,
        creatorUserId: owner.userId,
        creatorKeyId: vault.identity.keyId,
        recipients,
      }),
    );
    const response = await create(owner, { ...body, keys: { ...keys, keyVersionSignature: b64(signature) } });
    expect(response.status).toBe(422);
    expect(await stored(roomId)).toEqual({ rooms: 0, members: 0, versions: 0, envelopes: 0 });
  });

  it("refuses a creator key that is not the caller's ACTIVE identity (another user's, or retired)", async () => {
    const owner = await personWithVault(api, db);
    const other = await personWithVault(api, db);
    const body = await creationBody(owner, randomUUID());
    const foreign = { ...body, keys: { ...(body['keys'] as object), creatorKeyId: vaultOf(other).identity.keyId } };
    expect(errorCode(await create(owner, foreign))).toBe('IDENTITY_KEY_CHANGED');
    await db.query(
      `UPDATE user_key_pairs SET status = 'SUPERSEDED', superseded_at = now(), encrypted_private_key = NULL,
              encrypted_signing_private_key = NULL WHERE id = $1`,
      [vaultOf(owner).identity.keyId],
    );
    const response = await create(owner, await creationBody(owner, randomUUID()));
    expect(response.status).toBe(403);
    expect(errorCode(response)).toBe('VAULT_SETUP_REQUIRED');
  });

  it('stores key material only as the envelope: the server never holds RKM_1 (INV-04)', async () => {
    const owner = await personWithVault(api, db);
    const roomId = await createRoom(owner);
    const rkm = await roomKeyMaterial(owner, roomId);
    expect(rkm).toHaveLength(32);
    // No row of any room table, and no log line, contains the key material in any encoding.
    const needles = [rkm.toString('hex'), rkm.toString('base64'), rkm.toString('base64url')];
    for (const table of ['rooms', 'room_members', 'room_key_versions', 'key_envelopes', 'invitations']) {
      const column = table === 'rooms' ? 'id' : 'room_id';
      const { rows } = await db.query(`SELECT * FROM ${table} WHERE ${column} = $1`, [roomId]);
      const text = JSON.stringify(rows, (_key, value: unknown) =>
        value instanceof Buffer ? `${value.toString('hex')} ${value.toString('base64')}` : value,
      );
      for (const needle of needles) expect(text.includes(needle), table).toBe(false);
    }
    for (const needle of needles) expect(api.logText().includes(needle)).toBe(false);
  });
});

describe('what members fetch to verify the room key themselves (AZ-15, AZ-12, CM-T036)', () => {
  it("serves the genesis, the signed version 1, the signer identity and the caller's own envelope; the browser opens it", async () => {
    const owner = await personWithVault(api, db);
    const roomId = await createRoom(owner);
    const { material, envelopes } = await fetchKeyMaterial(owner, roomId);
    expect(material.genesis).toMatchObject({
      creatorUserId: owner.userId,
      creatorKeyId: vaultOf(owner).identity.keyId,
    });
    expect(material.keyVersions).toHaveLength(1);
    expect(material.keyVersions[0]).toMatchObject({
      keyVersion: 1,
      status: 'ACTIVE',
      previousCommitment: null,
      recipients: [{ userId: owner.userId, keyId: vaultOf(owner).identity.keyId }],
    });
    expect(material.identities.map((i) => i.keyId)).toEqual([vaultOf(owner).identity.keyId]);
    expect(envelopes).toHaveLength(1);
    const [opened] = await openRoom(owner, roomId);
    expect(opened?.keyVersion).toBe(1);
    expect(opened?.authorization).toEqual({ kind: 'recipient-list' });
  });

  it("serves envelopes by recipient only: a member never receives another member's envelope (OL-05)", async () => {
    const owner = await personWithVault(api, db);
    const joiner = await personWithVault(api, db);
    const roomId = await createRoom(owner);
    await inviteAndAccept(owner, roomId, joiner, 'MEMBER');
    const own = (await fetchKeyMaterial(joiner, roomId)).envelopes;
    expect(own.map((e) => e.recipientKeyId)).toEqual([vaultOf(joiner).identity.keyId]);
    const ownerOwn = (await fetchKeyMaterial(owner, roomId)).envelopes;
    expect(ownerOwn.map((e) => e.recipientKeyId)).toEqual([vaultOf(owner).identity.keyId]);
    // The joiner verifies through the OWNER's signed grant, not the version-1 recipient list.
    const [opened] = await openRoom(joiner, roomId);
    expect(opened?.authorization).toMatchObject({ kind: 'grant', role: 'MEMBER' });
    const [ownerKey] = await openRoom(owner, roomId);
    if (opened === undefined || ownerKey === undefined) throw new Error('rooms did not open');
    expect(await computeSafetyCode(opened)).toEqual(await computeSafetyCode(ownerKey));
  });

  it('a member without an envelope (added before Phase 6 style) gets no key to open', async () => {
    const owner = await personWithVault(api, db);
    const fixture = await personWithVault(api, db);
    const roomId = await createRoom(owner);
    await addMember(db, roomId, fixture.userId, 'MEMBER');
    expect(await keyBundles(fixture, roomId)).toEqual([]);
  });

  it('a room created before Phase 6 has no genesis and no key version (L-43)', async () => {
    const owner = await personWithVault(api, db);
    const legacy = randomUUID();
    await db.query(
      `INSERT INTO rooms (id, name, security_profile, policy_version, created_by_id) VALUES ($1, 'Legacy', 'STANDARD', 1, $2)`,
      [legacy, owner.userId],
    );
    await addMember(db, legacy, owner.userId, 'MEMBER');
    await db.query(`UPDATE room_members SET role = 'OWNER' WHERE room_id = $1`, [legacy]);
    const { material } = await fetchKeyMaterial(owner, legacy);
    expect(material.genesis).toBeNull();
    expect(material.keyVersions).toEqual([]);
    expect(await keyBundles(owner, legacy)).toEqual([]);
  });
});

describe('a server-side attacker cannot make members use a key of its own (T-36, T-29)', () => {
  it('an envelope replaced in the database fails the signed commitment (KEY_COMMITMENT_MISMATCH)', async () => {
    const owner = await personWithVault(api, db);
    const roomId = await createRoom(owner);
    const vault = vaultOf(owner);
    // The attacker knows only public keys: it wraps a key of its own to the owner.
    const attackerKey = new Uint8Array(randomBytes(32));
    const forged = await wrap32(
      vault.identity.encryptionPublicKey,
      attackerKey,
      contextBytes('cm.room.envelope', {
        roomId,
        keyVersion: 1,
        recipientUserId: owner.userId,
        recipientKeyId: vault.identity.keyId,
        suite: 'CM1',
      }),
    );
    await db.query('UPDATE key_envelopes SET wrapped_key = $2 WHERE room_id = $1', [roomId, Buffer.from(forged)]);
    await expect(openRoom(owner, roomId)).rejects.toMatchObject({ code: 'KEY_COMMITMENT_MISMATCH' });
    // The commitment itself is write-once in the database (it cannot be adjusted to match).
    await expect(
      db.query('UPDATE room_key_versions SET commitment = $2 WHERE room_id = $1', [roomId, DUMMY.digest()]),
    ).rejects.toThrow(/write-once/);
  });

  it('a key version written into the database without a valid signature is refused (KEY_AUTHENTICATION_FAILED)', async () => {
    const owner = await personWithVault(api, db);
    const roomId = await createRoom(owner);
    const vault = vaultOf(owner);
    const attackerKey = new Uint8Array(randomBytes(32));
    const commitment = Buffer.from(
      await (async () => {
        const { hkdfSync } = await import('node:crypto');
        return hkdfSync(
          'sha256',
          attackerKey,
          Buffer.alloc(32),
          contextBytes('cm.room.commitment', { roomId, keyVersion: 2 }),
          32,
        );
      })(),
    );
    const previous = await db.query<{ commitment: Buffer }>(
      'SELECT commitment FROM room_key_versions WHERE room_id = $1',
      [roomId],
    );
    await db.query(`UPDATE room_key_versions SET status = 'RETIRED', retired_at = now() WHERE room_id = $1`, [roomId]);
    await db.query(
      `INSERT INTO room_key_versions (room_id, version, status, commitment, algorithm_suite, reasons, created_by_id,
                                      created_by_key_id, previous_commitment, recipient_user_ids, recipient_key_ids, statement_signature)
       VALUES ($1, 2, 'ACTIVE', $2, 'CM1', '{MANUAL}', $3, $4, $5, $6, $7, $8)`,
      [
        roomId,
        commitment,
        owner.userId,
        vault.identity.keyId,
        previous.rows[0]?.commitment,
        [owner.userId],
        [vault.identity.keyId],
        DUMMY.signature(),
      ],
    );
    const envelope = await wrap32(
      vault.identity.encryptionPublicKey,
      attackerKey,
      contextBytes('cm.room.envelope', {
        roomId,
        keyVersion: 2,
        recipientUserId: owner.userId,
        recipientKeyId: vault.identity.keyId,
        suite: 'CM1',
      }),
    );
    await db.query(
      `INSERT INTO key_envelopes (room_id, key_version, recipient_user_id, recipient_key_id, status, wrapped_key, algorithm, created_by_id)
       VALUES ($1, 2, $2, $3, 'ACTIVE', $4, 'RSA-OAEP-3072-SHA256', $2)`,
      [roomId, owner.userId, vault.identity.keyId, Buffer.from(envelope)],
    );
    await db.query('UPDATE rooms SET current_key_version = 2 WHERE id = $1', [roomId]);
    await expect(openRoom(owner, roomId)).rejects.toMatchObject({ code: 'KEY_AUTHENTICATION_FAILED' });
  });
});

describe('key reports and Room Safety Code records carry the key version only (AZ-29, AZ-30, INV-18)', () => {
  it('records the events with the version and reason, and refuses any code field', async () => {
    const owner = await personWithVault(api, db);
    const roomId = await createRoom(owner);
    api.events.length = 0;
    const report = await owner.browser.request('POST', `/rooms/${roomId}/key-reports`, {
      keyVersion: 1,
      problem: 'COMMITMENT_MISMATCH',
    });
    expect(report.status).toBe(200);
    for (const result of ['MATCH', 'MISMATCH'] as const) {
      expect(
        (await owner.browser.request('POST', `/rooms/${roomId}/safety-code`, { keyVersion: 1, result })).status,
      ).toBe(200);
    }
    expect(api.events.map((e) => [e.name, e.details])).toEqual([
      ['ROOM_KEY_REJECTED', { roomId, keyVersion: 1, problem: 'COMMITMENT_MISMATCH' }],
      ['SAFETY_CODE_CONFIRMED', { roomId, keyVersion: 1 }],
      ['SAFETY_CODE_MISMATCH_REPORTED', { roomId, keyVersion: 1 }],
    ]);
    const [opened] = await openRoom(owner, roomId);
    if (opened === undefined) throw new Error('room did not open');
    const code = await computeSafetyCode(opened);
    const withCode = await owner.browser.request('POST', `/rooms/${roomId}/safety-code`, {
      keyVersion: 1,
      result: 'MATCH',
      words: code.words.join(' '),
    });
    expect(withCode.status).toBe(400);
    // The code never reaches the server: not in a request it accepted, not in a log line.
    for (const word of [code.words.join(' '), code.digits]) expect(api.logText().includes(word)).toBe(false);
  });

  it('a person who is not a member gets the generic 404 for every key route', async () => {
    const owner = await personWithVault(api, db);
    const stranger = await person(api);
    const roomId = await createRoom(owner);
    for (const [method, path, body] of [
      ['GET', `/rooms/${roomId}/key-versions`, undefined],
      ['GET', `/rooms/${roomId}/envelopes`, undefined],
      ['POST', `/rooms/${roomId}/key-reports`, { keyVersion: 1, problem: 'AUTHENTICATION_FAILED' }],
      ['POST', `/rooms/${roomId}/safety-code`, { keyVersion: 1, result: 'MATCH' }],
    ] as const) {
      const response = await stranger.browser.request(method, path, body);
      expect(response.status, path).toBe(404);
    }
  });
});

// A key package made for one identity is useless for another (the creator key binding).
describe('room creation keys bind the creator identity', () => {
  it('a package made with one vault does not create a room for another user', async () => {
    const owner = await personWithVault(api, db);
    const other: UnlockedVault = vaultOf(await personWithVault(api, db));
    const roomId = randomUUID();
    const { keys } = await createInitialRoomKey(other, roomId);
    const response = await create(owner, {
      roomId,
      name: 'Room',
      securityProfile: 'STANDARD',
      keys: roomCreationKeysToWire(keys),
    });
    expect(response.status).toBe(409);
    expect(await stored(roomId)).toEqual({ rooms: 0, members: 0, versions: 0, envelopes: 0 });
  });
});
