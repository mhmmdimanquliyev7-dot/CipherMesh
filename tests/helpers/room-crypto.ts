import type pg from 'pg';
import { expect } from 'vitest';
import { generateIdentity } from '../../packages/crypto/src/identity';
import { insertKeyPair } from './db-fixtures';

// Room cryptography for the API suites (Phase 6). People get REAL identities generated by
// packages/crypto (RSA-OAEP-3072 and ECDSA P-256, the browser code running in Node.js), because
// the API verifies every signed room statement; only the vault wrapping of the private keys is a
// DUMMY byte fixture (tests/helpers/db-fixtures.ts), since no test unlocks these vaults. The keys
// stay in memory in the test process, like an unlocked vault in a browser. Nothing is persisted.

export interface Identified {
  readonly userId: string;
  readonly browser: { request: (method: 'GET' | 'POST', path: string, body?: unknown) => Promise<Response> };
  readonly vault?: UnlockedVault;
}
type Response = { readonly status: number; readonly body: Record<string, unknown> };

/** Inserts a real public identity for the user (ACTIVE) and returns its keys as an unlocked vault. */
export async function insertIdentity(db: pg.Client, userId: string): Promise<UnlockedVault> {
  const generated = await generateIdentity(userId);
  const identity = generated.identity;
  await insertKeyPair(db, userId, {
    id: identity.keyId,
    public_key_spki: Buffer.from(identity.encryptionKeySpki),
    signing_public_key_spki: Buffer.from(identity.signingKeySpki),
    public_key_fingerprint: identity.fingerprint,
    identity_signature: Buffer.from(identity.bindingSignature),
  });
  return {
    identity,
    encryptionPrivateKey: generated.encryptionPrivateKey,
    signingPrivateKey: generated.signingPrivateKey,
  };
}

export function vaultOf(who: Identified): UnlockedVault {
  if (who.vault === undefined) throw new Error('this person has no identity; use personWithVault');
  return who.vault;
}

/** The body of POST /rooms with key version 1 made by the creator's keys (DF-05). */
export async function creationBody(
  who: Identified,
  roomId: string,
  securityProfile = 'STANDARD',
  name = 'Synthetic room',
): Promise<Record<string, unknown>> {
  const { keys } = await createInitialRoomKey(vaultOf(who), roomId);
  return { roomId, name, securityProfile, keys: roomCreationKeysToWire(keys) };
}

const b64 = (bytes: number): string => randomBytes(bytes).toString('base64url');

/** A key package of the right shape that no identity signed (random bytes, never a key). */
export const fillerKeys = (creatorKeyId: string) => ({
  creatorKeyId,
  commitment: b64(32),
  envelope: b64(384),
  genesisSignature: b64(64),
  keyVersionSignature: b64(64),
});

/** What a member's browser fetches to open the room's keys (AZ-15, AZ-12). */
export async function fetchKeyMaterial(who: Identified, roomId: string) {
  const material = await who.browser.request('GET', `/rooms/${roomId}/key-versions`);
  const envelopes = await who.browser.request('GET', `/rooms/${roomId}/envelopes`);
  expect(material.status, JSON.stringify(material.body)).toBe(200);
  expect(envelopes.status, JSON.stringify(envelopes.body)).toBe(200);
  return {
    material: material.body as unknown as RoomKeyMaterialWire,
    envelopes: envelopes.body['envelopes'] as EnvelopeWire[],
  };
}

export async function keyBundles(who: Identified, roomId: string): Promise<RoomKeyBundle[]> {
  const vault = vaultOf(who);
  const { material, envelopes } = await fetchKeyMaterial(who, roomId);
  return roomKeyBundlesFromWire(
    roomId,
    { userId: vault.identity.userId, keyId: vault.identity.keyId },
    material,
    envelopes,
  );
}

/** Opens the room's keys exactly as the browser does (ADR-015 section 4). */
export async function openRoom(who: Identified, roomId: string): Promise<OpenedRoomKey[]> {
  return openRoomKeys(vaultOf(who), await keyBundles(who, roomId));
}

/** The body of POST /rooms/{roomId}/invitations, made by the inviter's browser code. */
export async function invitationBody(
  inviter: Identified,
  roomId: string,
  invitee: Identified,
  role: 'ADMIN' | 'MEMBER' | 'VIEWER',
  confirmedFingerprint: string | null = null,
): Promise<Record<string, unknown>> {
  const keys = await createInvitationKeys(vaultOf(inviter), {
    roomId,
    bundles: await keyBundles(inviter, roomId),
    invitee: vaultOf(invitee).identity,
    role,
  });
  return {
    inviteeUserId: invitee.userId,
    inviteeKeyId: vaultOf(invitee).identity.keyId,
    role,
    confirmedFingerprint,
    ...invitationKeysToWire(keys),
  };
}

export async function invite(
  inviter: Identified,
  roomId: string,
  invitee: Identified,
  role: 'ADMIN' | 'MEMBER' | 'VIEWER',
  overrides: Record<string, unknown> = {},
): Promise<Response> {
  const body = { ...(await invitationBody(inviter, roomId, invitee, role)), ...overrides };
  return inviter.browser.request('POST', `/rooms/${roomId}/invitations`, body);
}

/** Invites and accepts; returns the invitation ID. Fails the test on any refusal. */
export async function inviteAndAccept(
  inviter: Identified,
  roomId: string,
  invitee: Identified,
  role: 'ADMIN' | 'MEMBER' | 'VIEWER',
  overrides: Record<string, unknown> = {},
): Promise<string> {
  const created = await invite(inviter, roomId, invitee, role, overrides);
  expect(created.status, JSON.stringify(created.body)).toBe(201);
  const id = (created.body['invitation'] as { id: string }).id;
  const accepted = await invitee.browser.request('POST', `/invitations/${id}/accept`, {});
  expect(accepted.status, JSON.stringify(accepted.body)).toBe(200);
  return id;
}

/** A grant of the right shape that nobody signed (for requests that authorization refuses first). */
export const fillerGrant = (): { subjectKeyId: string; signature: string } => ({
  subjectKeyId: '00000000-0000-4000-8000-000000000000',
  signature: b64(64),
});

/** A real grant when both people have identities, otherwise a well-formed filler. */
export async function grantOrFiller(
  grantor: Identified,
  roomId: string,
  target: Identified | undefined,
  role: 'ADMIN' | 'OWNER',
): Promise<{ subjectKeyId: string; signature: string }> {
  return grantor.vault !== undefined && target?.vault !== undefined
    ? grantProof(grantor, roomId, target, role)
    : fillerGrant();
}

/** A membership grant signed by `grantor` for the target's identity (AZ-05, AZ-10). */
export async function grantProof(
  grantor: Identified,
  roomId: string,
  target: Identified,
  role: 'ADMIN' | 'OWNER',
): Promise<{ subjectKeyId: string; signature: string }> {
  return grantProofToWire(
    await signMembershipGrant(vaultOf(grantor), { roomId, subject: vaultOf(target).identity, role }),
  );
}
