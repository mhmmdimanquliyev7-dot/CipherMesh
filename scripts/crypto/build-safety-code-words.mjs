// Builds the Room Safety Code word list (LIB-08, CP-24, ADR-012) from one pinned download:
//   packages/crypto/src/safety-code-words.ts
//
// Source: the BIP-39 English word list as shipped by trezor/python-mnemonic (MIT licence,
// Copyright (c) 2013-2016 Pavol Rusnak, one of the BIP-39 authors), pinned to a commit and checked
// against its SHA-256. The same bytes are published in bitcoin/bips (bip-0039/english.txt); the
// checksum below was compared with both on 2026-10-06. The list has exactly 2048 distinct
// lower-case words of 3 to 8 letters, chosen so that the first four letters identify a word and
// similar words are avoided, which suits reading the code aloud.
//
// The list is a public, fixed table: a word index carries 11 bits, six words carry 66 bits. It is
// not a secret and protects nothing by itself (L-22).
//
// Usage: node scripts/crypto/build-safety-code-words.mjs   (downloads, verifies, writes)
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';

const COMMIT = 'b57a5ad77a981e743f4167ab2f7927a55c1e82a8';
const URL = `https://raw.githubusercontent.com/trezor/python-mnemonic/${COMMIT}/src/mnemonic/wordlist/english.txt`;
const SHA256 = '2f5eed53a4727b4bf8880d8f3f199efc90e58503646d9ff8eff3a2ed3b24dbda';
const OUT = 'packages/crypto/src/safety-code-words.ts';

const response = await fetch(URL);
if (!response.ok) throw new Error(`download failed (${String(response.status)})`);
const bytes = Buffer.from(await response.arrayBuffer());
if (createHash('sha256').update(bytes).digest('hex') !== SHA256) throw new Error('checksum mismatch');
const words = bytes.toString('utf8').split('\n');
if (words.at(-1) === '') words.pop();
if (words.length !== 2048 || new Set(words).size !== 2048 || !words.every((w) => /^[a-z]{3,8}$/.test(w))) {
  throw new Error('unexpected word list shape');
}
if (new Set(words.map((w) => w.slice(0, 4))).size !== 2048) throw new Error('four-letter prefixes are not unique');

writeFileSync(
  OUT,
  [
    '// GENERATED by scripts/crypto/build-safety-code-words.mjs. Do not edit.',
    `// Source: trezor/python-mnemonic commit ${COMMIT} (MIT licence, Copyright (c) 2013-2016 Pavol Rusnak):`,
    `//   src/mnemonic/wordlist/english.txt sha256 ${SHA256}`,
    '// The BIP-39 English list: 2048 distinct words, identical to bitcoin/bips bip-0039/english.txt.',
    '// Room Safety Code display table (LIB-08, CP-24). Public data, not a secret.',
    `export const SAFETY_CODE_WORDS_TEXT: string = ${JSON.stringify(words.join('\n'))};`,
    `export const SAFETY_CODE_WORDS_SHA256 = '${SHA256}';`,
    '',
  ].join('\n'),
);
console.log(`wrote ${OUT}: ${String(words.length)} words`);
