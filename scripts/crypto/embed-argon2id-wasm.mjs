// Generates packages/crypto/src/kdf/argon2id-wasm.ts from the pinned `argon2id` package (LIB-03).
//
// The library ships two small WebAssembly binaries (with and without SIMD) and expects the
// bundler to load them. Embedding them as base64 in a generated module makes loading identical
// in Next.js, Vitest and Node.js, needs no extra static file and no connect-src change, and
// keeps the bytes reviewable: the module records each file's SHA-256, and a unit test fails if
// the embedded bytes ever differ from the installed package (for example after an update that
// was not regenerated).
//
// Usage: node scripts/crypto/embed-argon2id-wasm.mjs
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(new URL('../../packages/crypto/package.json', import.meta.url));
const root = dirname(require.resolve('argon2id/package.json'));
const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const files = { simd: 'simd.wasm', noSimd: 'no-simd.wasm' };
const OUT = 'packages/crypto/src/kdf/argon2id-wasm.ts';

const entries = Object.entries(files).map(([name, file]) => {
  const bytes = readFileSync(join(root, 'dist', file));
  return { name, file, base64: bytes.toString('base64'), sha256: createHash('sha256').update(bytes).digest('hex') };
});

writeFileSync(
  OUT,
  [
    '// GENERATED by scripts/crypto/embed-argon2id-wasm.mjs. Do not edit.',
    `// Source: npm package argon2id ${String(version)} (MIT licence, OpenPGP.js), files dist/simd.wasm and dist/no-simd.wasm.`,
    '// The unit test argon2id.test.ts compares these bytes with the installed package.',
    `export const ARGON2ID_PACKAGE_VERSION = ${JSON.stringify(version)};`,
    ...entries.flatMap((e) => [
      `/** dist/${e.file}, SHA-256 ${e.sha256} */`,
      `export const ARGON2ID_WASM_${e.name === 'simd' ? 'SIMD' : 'NO_SIMD'} = Object.freeze({`,
      `  file: ${JSON.stringify(`dist/${e.file}`)},`,
      `  sha256: ${JSON.stringify(e.sha256)},`,
      `  base64: ${JSON.stringify(e.base64)},`,
      '});',
    ]),
    '',
  ].join('\n'),
);
console.log(`wrote ${OUT} from argon2id ${String(version)}: ${entries.map((e) => `${e.file} ${e.sha256}`).join(', ')}`);
