// Builds the local blocklists of CP-06 from one pinned download:
//   - apps/api/src/auth/data/common-passwords.ts: account passwords, checked by the API (CM-T015);
//   - packages/crypto/src/passphrase-blocklist.ts: Vault Passphrases, checked only in the browser,
//     because the passphrase never leaves it (CM-T025, INV-01).
//
// Sources (SecLists, MIT licence, pinned commit, checksums verified):
//   - 100k-most-used-passwords-NCSC.txt: the UK NCSC list of the most common passwords in breaches
//   - Pwdb_top-1000000.txt: the one million most common passwords from public breach corpora
// Only entries that each policy could otherwise accept are kept (passwords 12 to 128 code points,
// passphrases 16 to 256 after NFKC), lower-cased and deduplicated. No password or passphrase is
// ever sent anywhere: both checks are local (T-09, T-22).
//
// Usage: node scripts/auth/build-password-blocklist.mjs   (downloads, verifies, writes)
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';

const COMMIT = '56da8d991239cc52b0da594db53457504a757670';
const BASE = `https://raw.githubusercontent.com/danielmiessler/SecLists/${COMMIT}/Passwords/Common-Credentials`;
const SOURCES = [
  {
    file: '100k-most-used-passwords-NCSC.txt',
    sha256: 'c2e5696882c603b76bb67a47ee970897e5a76fc4c3f5547abe3d0ca340c576e0',
  },
  { file: 'Pwdb_top-1000000.txt', sha256: 'e9a88f67aafe65496682dc374559ee714e978bee50314767494c3e37a18c9fc8' },
];
const OUT = 'apps/api/src/auth/data/common-passwords.ts';
const OUT_PASSPHRASES = 'packages/crypto/src/passphrase-blocklist.ts';
const LONE_SURROGATE = /[\uD800-\uDBFF](?![\uDC00-\uDFFF])|(?<![\uD800-\uDBFF])[\uDC00-\uDFFF]/u;

const entries = new Set();
const passphraseEntries = new Set();
for (const { file, sha256 } of SOURCES) {
  const response = await fetch(`${BASE}/${file}`);
  if (!response.ok) throw new Error(`download failed: ${file} (${String(response.status)})`);
  const bytes = Buffer.from(await response.arrayBuffer());
  const actual = createHash('sha256').update(bytes).digest('hex');
  if (actual !== sha256) throw new Error(`checksum mismatch for ${file}`);
  for (const line of bytes.toString('utf8').split(/\r?\n/)) {
    const normalized = line.normalize('NFKC').toLowerCase();
    const length = [...normalized].length;
    if (LONE_SURROGATE.test(normalized)) continue;
    if (length >= 12 && length <= 128) entries.add(normalized);
    if (length >= 16 && length <= 256) passphraseEntries.add(normalized);
  }
}

const sorted = [...entries].sort();
const body = JSON.stringify(sorted.join('\n'));
writeFileSync(
  OUT,
  [
    '// GENERATED by scripts/auth/build-password-blocklist.mjs. Do not edit.',
    `// Source: SecLists commit ${COMMIT} (MIT licence, Copyright (c) 2018 Daniel Miessler):`,
    ...SOURCES.map((s) => `//   ${s.file} sha256 ${s.sha256}`),
    `// ${String(sorted.length)} entries of 12 to 128 code points, NFKC-normalized and lower-cased.`,
    `export const COMMON_PASSWORDS: string = ${body};`,
    '',
  ].join('\n'),
);
console.log(`wrote ${OUT}: ${String(sorted.length)} entries`);

const sortedPassphrases = [...passphraseEntries].sort();
writeFileSync(
  OUT_PASSPHRASES,
  [
    '// GENERATED by scripts/auth/build-password-blocklist.mjs. Do not edit.',
    `// Source: SecLists commit ${COMMIT} (MIT licence, Copyright (c) 2018 Daniel Miessler):`,
    ...SOURCES.map((s) => `//   ${s.file} sha256 ${s.sha256}`),
    `// ${String(sortedPassphrases.length)} entries of 16 to 256 code points, NFKC-normalized and lower-cased.`,
    '// Checked only in the browser: the Vault Passphrase is never sent to the server (INV-01).',
    `export const COMMON_PASSPHRASES: string = ${JSON.stringify(sortedPassphrases.join('\n'))};`,
    '',
  ].join('\n'),
);
console.log(`wrote ${OUT_PASSPHRASES}: ${String(sortedPassphrases.length)} entries`);
